"""Candidate helper buttons for the pack routes (ruling 2026-09-14): each candidate's exact prefilled query, the chunk the phone's helper
route picks on the rebuilt packs under the stricter rule (eval/pack_rule.py helper, the PackRouter.helper mirror), and the answer the app
would show: the honest reply when the chunk fails the rule, otherwise the tamil-lm GGUF's reply to the same prompt the app builds
(core/Serving.kt: the tamil-lm system prompt; RetrievalLayer.groundHelper's context block with the chunk's first 1,500 characters and
the answer-only instruction, then the query; the chat template with thinking off), plus the source line the app appends.
Generation here is greedy (temperature 0) with llama.cpp on the host, so the wording is reproducible; the app samples at its temperature
setting (0.7 by default), so its wording can differ run to run. Candidates come from the pack content audit's reviewed gaps and the
Tamil University encyclopedia entries (eval/results/pack_content_audit.md, data/packs/agriculture/tamil_university_report.md).

  .venv/bin/python eval/pack_button_candidates.py   -> eval/results/pack_button_candidates.md and .json
"""
import json, os, re, subprocess, sys, time

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import pack_rule as R

MODEL = os.path.join(ROOT, "exports", "tamil-lm-2b-instruct-sft4c-Q4_K_M.gguf")
LLAMA = os.path.join(ROOT, "tools", "llama.cpp", "build", "bin", "llama-completion")
SYS_TAMIL_LM = "நீங்கள் தமிழ் மொழியில் உதவும் ஒரு உதவியாளர். துல்லியமாகவும் மரியாதையாகவும் பதிலளிக்கவும்."
INSTRUCTION = "மேலே உள்ள பகுதியை மட்டும் அடிப்படையாகக் கொண்டு பயனரின் கேள்விக்கு நேரடியாகப் பதிலளிக்கவும்; பகுதியில் இல்லாத செய்தியைச் சேர்க்க வேண்டாம். (Answer only from the passage above; add nothing that is not in it.)"
# (helper id, prefilled query, topic, pack)
CANDIDATES = [
    ("recipe", "Cooking recipe for sambar", "sambar", "cooking"), ("recipe", "Cooking recipe for idli", "idli", "cooking"),
    ("farming", "தென்னை சாகுபடி", "தென்னை", "agriculture"), ("farming", "கரும்பு சாகுபடி", "கரும்பு", "agriculture"),
    ("farming", "எள் சாகுபடி", "எள்", "agriculture"), ("farming", "உளுந்து சாகுபடி", "உளுந்து", "agriculture"), ("farming", "இஞ்சி சாகுபடி", "இஞ்சி", "agriculture"),
]

def detect_lang(text):   # SafetyLayer.detectLang
    if re.search(r"[஀-௿]", text): return "ta"
    if re.search(r"(?i)\b(enna|epdi|eppadi|sollu|sollunga|illa|irukku|irukka|panna|pannu|venum|naan|nee|nenga|neenga|la|ku|oda)\b", text): return "tanglish"
    return "en"

def generate(user):
    prompt = f"<|im_start|>system\n{SYS_TAMIL_LM}<|im_end|>\n<|im_start|>user\n{user}<|im_end|>\n<|im_start|>assistant\n<think>\n\n</think>\n\n"
    r = subprocess.run([LLAMA, "-m", MODEL, "-p", prompt, "-n", "300", "--temp", "0", "-no-cnv", "-t", "8", "-c", "4096", "--no-display-prompt"],
                       capture_output=True, text=True, timeout=900)
    out = r.stdout
    return re.sub(r"<think>.*?</think>", "", out, flags=re.S).replace("<|im_end|>", "").strip()

def main():
    P = R.load_packs(os.path.join(ROOT, "dist", "app_packs", "packs")); rows = []
    for hid, query, topic, pack in CANDIDATES:
        x = R.helper(P, pack, topic, True, R.STRICT); h = x["hit"]; c = x["confidence"] or {}
        lang = detect_lang(query)
        rec = {"helper": hid, "query": query, "topic": topic, "pack": pack, "kind": x["kind"], "chunk": R.chunk_id(h) if h else None, "title": h["title"] if h else None,
               "coverage": round(c.get("coverage", 0), 2), "proc": round(c.get("proc", 0), 1)}
        if x["kind"] == "pack":
            block = f"[pack_{pack}: {h['title']}]\n{h['text'][:1500]}\n\n{INSTRUCTION}\n\n"
            reply = generate(block + query)
            source = f"{h['title']}, {h['meta'].get('source', 'pack_' + pack)}"
            rec.update({"passage": h["text"][:1500], "answer": reply + "\n\n" + ("மூலம்: " if lang == "ta" else "source: ") + source})
        else:
            rec.update({"answer": x.get("reply")})
        rows.append(rec); print(hid, query, rec["kind"], rec["chunk"], flush=True)
    L = [f"# Candidate helper buttons for the pack routes ({time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())})", "",
         "Generated by eval/pack_button_candidates.py on the rebuilt packs under the stricter rule; answers from the tamil-lm Q4_K_M GGUF, greedy, with the app's prompt. Not wired into the app.", ""]
    for r in rows:
        L += [f"## {r['helper']}: \"{r['query']}\"", "", f"- route: {r['pack']} pack, topic \"{r['topic']}\"; decision: {r['kind']}; chunk {r['chunk']} ({r['title']}); coverage {r['coverage']}, procedure markers per 100 words {r['proc']}", ""]
        if r.get("passage"): L += ["Passage the model gets (first 1,500 characters):", "", "```", r["passage"], "```", ""]
        L += ["Answer the app would show:", "", "```", r["answer"] or "", "```", ""]
    open(os.path.join(HERE, "results", "pack_button_candidates.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    json.dump(rows, open(os.path.join(HERE, "results", "pack_button_candidates.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

if __name__ == "__main__":
    main()
