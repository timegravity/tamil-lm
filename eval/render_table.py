"""Render the README results table from eval/results/*.json. Numbers are never
hand-edited: this script is the only writer of the table block in README.md
(between <!-- RESULTS:BEGIN --> and <!-- RESULTS:END -->).

Usage: python eval/render_table.py [--write]
"""
import argparse, glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import suite

from table_guard import MissingResult
STAGES = ["base", "cpt_final", "sft_final", "sft4_final"]
LEGEND = "base = Qwen/Qwen3.5-2B-Base before any Tamil training; cpt_final = tamil-lm-2b-base (this release); sft_final = an earlier instruct model, not released; sft4_final = tamil-lm-2b-instruct (this release)."
# Metrics added after a stage's locked run: rendered as the explicit reason, never blank (locked test runs are never repeated).
LATER_METRICS = {("indicqa_ta", "contains"): "added later", ("tamil_heldout", "bpc"): "added later"}

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    cells = {}   # (bench, metric, stage, split) -> (score, n, commit)
    for fn in glob.glob(os.path.join(suite.RESULTS, "*_dev.json")) + \
              glob.glob(os.path.join(suite.RESULTS, "*_test.json")):
        for r in json.load(open(fn)):
            if isinstance(r, dict) and r.get("stage") in STAGES and "benchmark" in r:
                cells[(r["benchmark"], r["metric"], r["stage"], r["split"])] = (r["score"], r["n"], r["commit"])
    keys = sorted({(b, m) for (b, m, _, _) in cells})
    cols = [(s, sp) for s in STAGES for sp in ("dev", "test") if os.path.exists(os.path.join(suite.RESULTS, f"{s}_{sp}.json"))]   # a column that never ran is dropped, not blank
    head = "| benchmark | metric | " + " | ".join(f"{s} {sp}" for s, sp in cols) + " |"
    sep = "|" + "---|" * (2 + len(cols))
    lines = [head, sep]
    for b, m in keys:
        row = [b, m]
        for s, sp in cols:
            c = cells.get((b, m, s, sp))
            if not c:
                if (b, m) in LATER_METRICS:
                    row.append(f"not scored: metric {LATER_METRICS[(b, m)]}, after this run"); continue
                raise MissingResult(f"{b} {m} missing from {s}_{sp}.json (ruling 2026-09-12: a missing result key fails the table)")
            row.append(f"{c[0]:.3f} (n={c[1]})")
        lines.append("| " + " | ".join(row) + " |")
    commits = sorted({c[2] for c in cells.values()})
    lines.append("")
    lines.append(LEGEND)
    lines.append("Generated by eval/render_table.py from the result files. Each test column was run exactly once per model. "
                 "Literature probe (eval/run_probe.py) is the primary metric and is reported separately.")
    table = "\n".join(lines)
    print(table)
    if a.write:
        p = os.path.join(os.path.dirname(suite.HERE), "README.md")
        s = open(p).read()
        b, e = "<!-- RESULTS:BEGIN -->", "<!-- RESULTS:END -->"
        if b not in s:
            s += f"\n\n## Benchmark results\n{b}\n{e}\n"
        pre, rest = s.split(b); _, post = rest.split(e)
        open(p, "w").write(f"{pre}{b}\n{table}\n{e}{post}")
        print("README.md table updated")

if __name__ == "__main__":
    main()
