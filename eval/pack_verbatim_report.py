"""Verbatim pack answers (ruling 2026-09-14, option b): the button candidates as the phone shows them, and the held-out set under the new display.

Inputs:
  dist/parity/button_verbatim_phone.json  written by PackStrictParityTest (the Kotlin Helpers, PackRouter, PackIndex and PackRule classes on
                                          the shipped pack files; it is the authority for what the app displays), including the reply check
                                          (FamilySafe lexicon backstop and the guard classifier) on the displayed text;
  dist/parity/pack_strict_parity.json     the host mirror's decisions (eval/pack_rule.py --parity), which the same test compares row by row;
  eval/pack_heldout_questions.jsonl       the held-out questions.
Held-out outcomes: honest reply, no pack, wrong pack and controls come from the decision; for questions answered from the expected pack
the judgement below was made by reading the text: for a verbatim answer the displayed passage, for a grounded answer (the model writes
the reply) the passage given to the model. Useful: the passage itself contains the information the question asks for, as asked (a recipe
or method with its steps for a how question, the fact for a what question). Weak: on the topic, but without that information.

  .venv/bin/python eval/pack_verbatim_report.py   -> eval/results/pack_button_candidates_verbatim.md
"""
import json, os, sqlite3, sys, time

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import pack_rule as R

# read and judged 2026-09-14 (held-out id -> (judgement, what the passage holds)); only rows answered from the expected pack need one
JUDGED = {
    "ho-003": ("weak", "verbatim: the upma article lead, types of upma, no method"),
    "ho-008": ("useful", "verbatim: Wikibooks lemon rice ingredients and procedure"),
    "ho-018": ("useful", "grounded: Wikibooks appam recipe; yeast or kefir, grind, leave to rise overnight"),
    "ho-038": ("weak", "grounded: okra yields in Florida, not groundnut seed rate"),
    "ho-040": ("weak", "verbatim: mushroom kinds, no growing method"),
    "ho-047": ("weak", "grounded: taxes merged into GST and its structure; the expansion only in the Tamil title"),
    "ho-050": ("weak", "grounded: the EPFO pension scheme 1995, not a general answer to what a pension scheme is"),
    "ho-054": ("weak", "grounded: EPFO FAQ on the employer's share after 55 or 60, not who contributes"),
    "ho-062": ("useful", "grounded: definition of the Kisan Credit Card"),
    "ho-068": ("useful", "grounded: medicinal uses of hibiscus flowers"),
    "ho-074": ("weak", "grounded: lemon butterfly description and number of generations, not the life-cycle stages"),
    "ho-078": ("useful", "grounded: jamun tree description"),
}
KEYS = ["useful", "weak", "wrong pack", "honest reply", "no pack"]
# Vignesh's per-button ruling of 2026-09-14: only approved buttons ship (core/Helpers.kt; HelperRoutesTest enforces the list)
APPROVAL = {"Cooking recipe for sambar": "rejected", "Cooking recipe for idli": "approved, ships", "தென்னை சாகுபடி": "rejected", "கரும்பு சாகுபடி": "approved, ships",
            "எள் சாகுபடி": "rejected", "உளுந்து சாகுபடி": "rejected", "இஞ்சி சாகுபடி": "approved, ships"}

def main():
    phone = json.load(open(os.path.join(ROOT, "dist", "parity", "button_verbatim_phone.json"), encoding="utf-8"))["buttons"]
    host = json.load(open(os.path.join(ROOT, "dist", "parity", "pack_strict_parity.json"), encoding="utf-8"))
    hrows = {r["helper_query"]: r for r in host["rows"] if "helper_query" in r}
    qrows = {r["q"]: r for r in host["rows"] if "q" in r}
    held = [json.loads(l) for l in open(os.path.join(HERE, "pack_heldout_questions.jsonl"), encoding="utf-8") if l.strip()]
    # longest verbatim display over every chunk of the verbatim packs (Tamil-script question: the longer source labels)
    longest = (0, None)
    for n in sorted(R.VERBATIM_PACKS):
        con = sqlite3.connect(os.path.join(ROOT, "dist", "app_packs", "packs", f"{n}.sqlite"))
        for t, x, m in con.execute("SELECT title, text, meta FROM docs"):
            d = R.display({"title": t, "text": x, "meta": json.loads(m or "{}")}, "அ")
            if len(d) > longest[0]: longest = (len(d), json.loads(m or "{}").get("id"))
    L = [f"# Pack button candidates, verbatim display ({time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())})", "",
         "Generated by eval/pack_verbatim_report.py from the phone's own output (PackStrictParityTest runs the Kotlin classes on the shipped pack files) "
         "and the host mirror (eval/pack_rule.py). Vignesh's ruling of 2026-09-14: approved and shipped: \"Cooking recipe for idli\", \"கரும்பு சாகுபடி\", \"இஞ்சி சாகுபடி\"; rejected: sambar, coconut, sesame, black gram (kept below as the record of what was reviewed).", "",
         "Display rule: a helper with the how flag (recipe, farming) or a typed question matched by the stricter rule's how_regex, answered by a chunk that passed PACK_STRICT_V1 in the cooking or agriculture pack, is shown without the model: "
         "the chunk title as a heading line, a blank line, the passage exactly as stored after the generated header (the section-list line is dropped; a Tamil University encyclopedia chunk's volume and page line moves into the source line), a blank line, and the source line "
         "(title, part of a split article, site, citation, licence as stored). No URL: the shipped pack files do not carry page URLs. The reply check (lexicon backstop, blocked terms allowed for agriculture and nature, and the guard) runs on the displayed text.",
         f"Longest possible verbatim display over all cooking and agriculture chunks: {longest[0]} characters ({longest[1]}).", ""]
    same_all = True
    for b in phone:
        h = hrows.get(b["query"]); same = bool(h) and h["chunk"] == b["chunk"] and h["display"] == b["display"] and h["verbatim"] == (b["decision"] == "pack passage verbatim")
        same_all &= same
        L += [f"## \"{b['query']}\" ({APPROVAL[b['query']]}, Vignesh 2026-09-14)", "",
              f"- helper: {b['helper']}, topic \"{b['topic']}\", pack {b['pack']}; decision: {b['decision']}; chunk {b['chunk']}; coverage {b['coverage']}, procedure markers per 100 words {round(b['proc'], 1) if b['proc'] is not None else None}",
              f"- reply check on the displayed text: {'blocked' if b['reply_check_blocked'] else 'passes'} (guard unsafe probability {round(b['guard_unsafe_probability'], 3) if b['guard_unsafe_probability'] is not None else None}); host mirror identical: {same}; displayed length {len(b['display'] or '')} characters", "",
              "Displayed text, unabridged:", "", "```", b["display"] or "", "```", ""]
    counts = {k: 0 for k in KEYS}; ctl = {"answered": 0, "honest reply": 0, "no pack": 0}; per = []
    for r in held:
        x = qrows[r["q"]]; exp = r.get("expect_pack")
        if x["kind"] == "no_info": o = "honest reply"
        elif x["kind"] == "none": o = "no pack"
        elif not exp: o = "answered"
        elif x["pack"] != exp: o = "wrong pack"
        else: o = JUDGED[r["id"]][0]
        if exp: counts[o] += 1
        else: ctl[o] += 1
        per.append((r, x, o))
    L += ["## Held-out set under the new display", "",
          f"Pack questions: {sum(1 for r in held if r.get('expect_pack'))}; controls: {sum(1 for r in held if not r.get('expect_pack'))}. Stricter rule, rebuilt packs. Verbatim answers among them: {sum(1 for r, x, o in per if x['verbatim'])}.", "",
          "| useful | weak | wrong pack | honest reply | no pack | controls answered | controls honest reply | controls no pack |", "|---|---|---|---|---|---|---|---|",
          f"| {counts['useful']} | {counts['weak']} | {counts['wrong pack']} | {counts['honest reply']} | {counts['no pack']} | {ctl['answered']} | {ctl['honest reply']} | {ctl['no pack']} |", "",
          "| id | question | expected pack | outcome | shown | chunk | reading |", "|---|---|---|---|---|---|---|"]
    for r, x, o in per:
        if o == "no pack" or (not r.get("expect_pack") and o == "no pack"): continue
        shown = "verbatim passage" if x["verbatim"] else ("honest reply" if x["kind"] == "no_info" else ("model reply from the passage" if x["kind"] == "pack" else "-"))
        L.append(f"| {r['id']} | {r['q']} | {r.get('expect_pack') or 'control'} | {o} | {shown} | {x['chunk'] or '-'} | {JUDGED.get(r['id'], ('', ''))[1]} |")
    L += ["", f"Phone and host displayed texts identical for all {len(phone)} buttons: {same_all}."]
    open(os.path.join(HERE, "results", "pack_button_candidates_verbatim.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(counts, ctl, "same", same_all, "longest", longest)

if __name__ == "__main__":
    main()
