"""The pack rules on the held-out pack questions (eval/pack_heldout_questions.jsonl), which no gate or rule was tuned on.

The held-out set (2026-09-14): 100 questions written fresh from each pack's topic taxonomy (dishes and techniques; crops, pests, soil and
practice; banking, tax, insurance and savings terms; plants, birds and animals) plus general controls, in Tamil, Tanglish and English;
none repeats a question of the pack question or routing files, the pack audit, or the app's tests. Each was labelled by reading the
rebuilt pack chunks (build of 2026-09-14): the pack that should answer, whether a chunk in it really answers the question
(answerable), and the answer words a useful chunk carries (expect_terms, at least half must be in the text the model sees); label_basis
names the chunks. One draft control about cattle fodder was relabelled as an agriculture question after reading.

Outcomes per question, through the typed route of the app (all four domain packs on) in eval/pack_rule.py:
  useful: the expected pack answers an answerable question with at least half of its expect_terms in the first 1,500 characters;
  weak: the expected pack answers, but the chunk lacks the terms, or the question is one the pack cannot answer well;
  wrong pack: another pack answers a pack question;
  honest reply: a pack fired and the stricter rule replaced its chunk with "I do not have good information on this";
  no pack: no pack fired (plain generation);
  control answered: any pack answers a control.
Rows: today's rule on the pack files shipped before the rebuild, today's rule on the rebuilt files, the stricter rule on the rebuilt files.

  .venv/bin/python eval/pack_heldout_eval.py --before-dir DIR   -> eval/results/pack_heldout_eval.md and .json
"""
import argparse, hashlib, json, os, re, sys, time

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import pack_rule as R
import calibrate_device_gates as D

def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()[:12]

def useful_terms(hit, row):
    terms = row.get("expect_terms") or []
    win = hit["text"][:R.STRICT["window"]].lower()
    return bool(terms) and sum(1 for t in terms if t.lower() in win) * 2 >= len(terms)

def outcome(x, row):
    exp = row.get("expect_pack")
    if x["kind"] == "no_info": return "control honest reply" if not exp else "honest reply"
    if x["kind"] == "none": return "control no pack" if not exp else "no pack"
    if not exp: return "control answered"
    if x["pack"] != exp: return "wrong pack"
    return "useful" if row.get("answerable") and useful_terms(x["hit"], row) else "weak"

def run(P, rows, strict):
    per = []
    for r in rows:
        x = R.route(P, r["q"], strict)
        c = x.get("confidence") or {}
        per.append({"id": r["id"], "outcome": outcome(x, r), "pack": x["pack"], "chunk": R.chunk_id(x["hit"]) if x["hit"] else None,
                    "coverage": round(c["coverage"], 2) if c else None, "proc": round(c["proc"], 1) if c else None})
    return per

KEYS = ["useful", "weak", "wrong pack", "honest reply", "no pack", "control answered", "control honest reply", "control no pack"]

def counts(per, rows, subset=None):
    ids = {r["id"] for r in rows if subset is None or subset(r)}
    return {k: sum(1 for p in per if p["id"] in ids and p["outcome"] == k) for k in KEYS}

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--before-dir", required=True); ap.add_argument("--after-dir", default=os.path.join(ROOT, "dist", "app_packs", "packs")); a = ap.parse_args()
    rows = [json.loads(l) for l in open(os.path.join(HERE, "pack_heldout_questions.jsonl"), encoding="utf-8") if l.strip()]
    D.translit_batch([t for r in rows for t in D.phone_tokens(r["q"]) if re.fullmatch(r"[a-z]+", t) and len(t) >= 3 and not D.english(t)])
    before = R.load_packs(os.path.abspath(a.before_dir)); after = R.load_packs(os.path.abspath(a.after_dir))
    runs = [("today's rule, packs before the rebuild", run(before, rows, None)), ("today's rule, rebuilt packs", run(after, rows, None)), ("stricter rule, rebuilt packs", run(after, rows, R.STRICT))]
    groups = [("all pack questions", lambda r: r.get("expect_pack")), ("answerable pack questions", lambda r: r.get("expect_pack") and r.get("answerable")),
              ("pack questions the pack cannot answer well", lambda r: r.get("expect_pack") and r.get("answerable") is False), ("controls", lambda r: not r.get("expect_pack"))]
    n_ans = sum(1 for r in rows if r.get("expect_pack") and r.get("answerable")); n_un = sum(1 for r in rows if r.get("expect_pack") and r.get("answerable") is False); n_ctl = sum(1 for r in rows if not r.get("expect_pack"))
    L = [f"# Pack rules on the held-out pack questions ({time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())})", "",
         "Generated by eval/pack_heldout_eval.py. Questions: eval/pack_heldout_questions.jsonl (never used to tune a gate or the rule; how it was made is in the script's docstring): "
         f"{n_ans} answerable pack questions, {n_un} pack questions the pack cannot answer well, {n_ctl} controls. Route: all four domain packs on, as eval/pack_rule.py mirrors the app.",
         "Pack files: before the rebuild " + ", ".join(f"{n} {sha(os.path.join(a.before_dir, n + '.sqlite'))}" for n in R.PACKS) + "; rebuilt " + ", ".join(f"{n} {sha(os.path.join(a.after_dir, n + '.sqlite'))}" for n in R.PACKS) + " (sha256, first 12).", ""]
    for label, sub in groups:
        L += [f"## {label}", "", "| rule | " + " | ".join(KEYS) + " |", "|---" * (len(KEYS) + 1) + "|"]
        for name, per in runs:
            c = counts(per, rows, sub); L.append(f"| {name} | " + " | ".join(str(c[k]) for k in KEYS) + " |")
        L.append("")
    L += ["## Per question", "", "| id | lang | expected pack | answerable | " + " | ".join(n for n, _ in runs) + " |", "|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows):
        cells = [f"{per[i]['outcome']} ({per[i]['pack'] or '-'}, {per[i]['chunk'] or '-'}{', cov ' + str(per[i]['coverage']) + ', proc ' + str(per[i]['proc']) if per[i]['coverage'] is not None else ''})" for _, per in runs]
        L.append(f"| {r['id']} {r['q']} | {r['lang']} | {r.get('expect_pack') or 'control'} | {r.get('answerable')} | " + " | ".join(cells) + " |")
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    open(os.path.join(HERE, "results", "pack_heldout_eval.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    json.dump({"runs": {n: {"all": counts(p, rows), **{g: counts(p, rows, s) for g, s in groups}, "per_question": p} for n, p in runs}}, open(os.path.join(HERE, "results", "pack_heldout_eval.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("\n".join(L[:40]))

if __name__ == "__main__":
    main()
