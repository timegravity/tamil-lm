"""Tokenizer extension record (the card's tokenizer numbers, regenerated from sources, never hand-copied).

Computes, from the released tokenizer and the base tokenizer:
  - added_tokens, base_vocab_size and vocab_size_new, with the vocabulary measure named in the output
    (len(tokenizer) counts the base model's 33 special added tokens, tokenizer.vocab_size does not; only the
    first reproduces the 248,077 the build recorded), asserting base + added == new;
  - fertility (tokens per word) on the same two texts the card quotes: the first 300 Tamil sentences of the
    FLORES held-out split, and the 10,000 Tamil Wikipedia sentences the tokenizer build used, rebuilt from the
    pinned dump revision in the dump's own order (no sampling, no seed: the build took the first 10,000 sentences
    of three words or more, splitting each article on [.!?\n]+), with a SHA-256 over the joined sentences recorded
    so a rebuilt set can be shown to be the same set even if the dataset is re-uploaded.

  .venv/bin/python eval/tokenizer_extension_report.py [--no-wikipedia]  -> eval/results/tokenizer_extension.json
"""
import argparse, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
BASE = "Qwen/Qwen3.5-2B-Base"
RELEASED = "ckpt/final/tamil-lm-2b-instruct-sft4c-vl"
WIKI = ("wikimedia/wikipedia", "20231101.ta")   # the dump the tokenizer build measured on
WIKI_REVISION = "b04c8d1ceb2f5cd4588862100d08de323dccfbaa"   # pinned, so a re-upload of the dataset cannot change the set
OUT = os.path.join(HERE, "results", "tokenizer_extension.json")
SOURCE = ("Every value in this file is regenerated by eval/tokenizer_extension_report.py: the vocabulary counts from the two tokenizers "
          "themselves, and each fertility (tokens per word) from the text named beside it. Nothing is copied by hand.")
REPRODUCTION = ("Regenerated on 2026-09-20 from the pinned dump, this reproduces the tokenizer build of 2026-09-11 08:11 UTC to three "
                "decimals: 6.486 and 1.916 tokens per word on the 10,000 Tamil Wikipedia sentences, matching that build's "
                "fertility_report.json; the effective Tamil context in words differs by one (2,138 against 2,137) from rounding.")

def fertility(tok, texts):
    words = sum(len(t.split()) for t in texts)
    return sum(len(tok(t, add_special_tokens=False).input_ids) for t in texts) / max(1, words)

def wikipedia_sentences(n=10000):
    from datasets import load_dataset
    ds = load_dataset(WIKI[0], WIKI[1], split="train", streaming=True, revision=WIKI_REVISION)
    sents = []
    for doc in ds:
        for s in re.split(r"[.!?\n]+", doc["text"]):
            s = s.strip()
            if len(s.split()) >= 3: sents.append(s)
        if len(sents) >= n: break
    return sents[:n]

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--no-wikipedia", action="store_true"); a = ap.parse_args()
    from transformers import AutoTokenizer
    import baselines_round4 as B
    base = AutoTokenizer.from_pretrained(BASE, trust_remote_code=True)
    new = AutoTokenizer.from_pretrained(os.path.join(ROOT, RELEASED), trust_remote_code=True)
    measure = "len(tokenizer)"   # includes the base model's special added tokens; tokenizer.vocab_size excludes them
    base_v, new_v = len(base), len(new)
    added = new_v - base_v
    assert base_v + added == new_v, f"{base_v} + {added} != {new_v}"
    assert added == 22222, f"added tokens {added}, expected 22222 (the build's count)"
    r = {"vocabulary_measure": measure, "vocabulary_measure_note": f"tokenizer.vocab_size is {base.vocab_size} for both tokenizers and does not count added tokens",
         "base_vocab_size": base_v, "added_tokens": added, "vocab_size_new": new_v,
         "base_tokenizer": BASE, "released_tokenizer": RELEASED}
    ids = json.load(open(os.path.join(HERE, "splits", "tamil_heldout.json")))["dev"][:300]
    import bench_loaders_understanding as L
    by = {it["id"]: it["text"] for it in L.load_tamil_heldout()}
    flores = [by[i] for i in ids if i in by]
    r["flores_sentences"] = len(flores)
    r["fertility_old_flores"] = round(fertility(base, flores), 3)
    r["fertility_new_flores"] = round(fertility(new, flores), 3)
    if not a.no_wikipedia:
        sents = wikipedia_sentences()
        import hashlib
        r["wikipedia_dump"] = f"{WIKI[0]} {WIKI[1]}, first {len(sents)} sentences of three words or more, in dump order"
        r["wikipedia_dump_revision"] = WIKI_REVISION
        r["wikipedia_sentences_sha256"] = hashlib.sha256("\n".join(sents).encode("utf-8")).hexdigest()   # proves a rebuilt set is the same set
        r["wikipedia_sentences"] = len(sents)
        r["fertility_old_wikipedia"] = round(fertility(base, sents), 3)
        r["fertility_new_wikipedia"] = round(fertility(new, sents), 3)
        r["effective_context_words_old"] = round(4096 / r["fertility_old_wikipedia"])
        r["effective_context_words_new"] = round(4096 / r["fertility_new_wikipedia"])
    r["_source"] = SOURCE
    r["_reproduction"] = REPRODUCTION
    r["_regenerated_by"] = "eval/tokenizer_extension_report.py"
    json.dump(r, open(OUT, "w"), indent=1); open(OUT, "a").write("\n")
    print(json.dumps(r, indent=1))

if __name__ == "__main__":
    main()
